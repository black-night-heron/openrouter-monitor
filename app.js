/** Resolve the active theme: an explicit localStorage choice wins over the
 *  OS preference. The pre-paint script in index.html already applied it. */
function resolvedTheme() {
  try {
    const stored = localStorage.getItem(THEME_KEY)
    if (stored === 'light' || stored === 'dark') return stored
  } catch { /* localStorage blocked — fall back to the OS signal */ }
  return matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'
}

function setupTheme() {
  const btn = $('#theme-toggle')
  const mq = matchMedia('(prefers-color-scheme: dark)')

  function apply() {
    const theme = resolvedTheme()
    document.documentElement.setAttribute('data-theme', theme)
    if (btn) {
      const next = theme === 'dark' ? 'light' : 'dark'
      btn.setAttribute('aria-label', `Switch to ${next} theme`)
      btn.setAttribute('title', `Switch to ${next} theme`)
    }
    // Charts bake grid/tick colors in at build time, so they must be rebuilt.
    if (uptimeChart) loadModelUptimeChart()
    if (radarChart) renderRadarChart()
  }

  // Only follow OS changes while the user has NOT made an explicit choice.
  mq.addEventListener('change', () => {
    let stored = null
    try { stored = localStorage.getItem(THEME_KEY) } catch { /* blocked */ }
    if (!stored) apply()
  })

  btn?.addEventListener('click', () => {
    const next = resolvedTheme() === 'dark' ? 'light' : 'dark'
    try { localStorage.setItem(THEME_KEY, next) } catch { /* blocked */ }
    apply()
  })

  apply()
}

