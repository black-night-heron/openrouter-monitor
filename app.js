// ── Data Fetch ──────────────────────────────────────────────────────────────
/** Fetch a JSON snapshot with a cache-busting param — otherwise the CDN
 *  may serve a stale copy between the 10-minute regenerations. */
async function fetchJson(url) {
  const resp = await fetch(`${url}?t=${Date.now()}`, { cache: 'no-store' })
  if (!resp.ok) throw new Error(`HTTP ${resp.status} while loading ${url}`)
  return resp.json()
}

/** Flat (model, provider) view for the models table; a model without
 *  providers still contributes one row. */
function flattenModels(models) {
  const rows = []
  for (const m of models) {
    if (!m.providers.length) {
      rows.push({ ...m, provider: null })
      continue
    }
    for (const p of m.providers) rows.push({ ...m, provider: p })
  }
  return rows
}

async function refresh() {
  if (refreshInFlight) return
  refreshInFlight = true

  try {
    const data = await fetchJson('data/dashboard.json')
    dashboard = data
    allModels = data.models || []
    allRows = flattenModels(allModels)

    if (!hasInitializedSelection && selectedModelIds.size === 0) {
      const picks = topByUptime(allModels, 5)
      if (picks.length < 5) {
        for (const m of allModels) {
          if (picks.length >= 5) break
          if (!picks.includes(m)) picks.push(m)
        }
      }
      for (const m of picks) selectedModelIds.add(m.id)
      hasInitializedSelection = true
    }

    renderSummary(data.summary)
    renderModels(allRows)
    populateOwnerFilters(allModels)
    populateModelSelect(allModels)
    // Keep already-open tabs in sync; the lazily-fetched grid refetches on reset.
    if (uptimeLoaded) {
      uptimePayload = null
      loadModelUptimeChart()
    }
    if (benchHasLoaded) refreshBenchmarks()
  } catch (err) {
    console.error('Dashboard fetch error:', err)
  } finally {
    refreshInFlight = false
  }
}

async function ensureUptime() {
  if (!uptimePayload) uptimePayload = await fetchJson('data/uptime.json')
  return uptimePayload
}

/** Window + model filtering on the columnar grid — the snapshot carries
 *  every free model, so range/selection switches cost nothing. */
function sliceUptime(uptime, hours, ids) {
  if (!uptime || !uptime.n) return { timestamps: [], datasets: [] }
  const cutoff = Date.now() - hours * 60 * 60 * 1000
  const start = Math.max(0, Math.ceil((cutoff - uptime.t0) / uptime.step))
  if (start >= uptime.n) return { timestamps: [], datasets: [] }
  const idSet = new Set(ids)
  const timestamps = []
  for (let i = start; i < uptime.n; i++) timestamps.push(uptime.t0 + i * uptime.step)
  const datasets = []
  uptime.models.forEach((m, i) => {
    if (!idSet.has(m.id)) return
    datasets.push({
      modelId: m.id,
      owner: m.owner,
      name: m.name,
      availability: uptime.series[i].slice(start),
    })
  })
  return { timestamps, datasets }
}

/** Top-N models by 24h availability, stable name tiebreak for 100% ties. */
function topByUptime(models, n) {
  // .filter guarantees a non-null uptime, so a plain subtract is safe.
  return [...models]
    .filter((m) => m.uptime1dAvg != null)
    .sort((a, b) => {
      const u = b.uptime1dAvg - a.uptime1dAvg
      return u !== 0 ? u : a.name.localeCompare(b.name)
    })
    .slice(0, n)
}

