function switchTab(tabName) {
  $$('.tab').forEach((t) => {
    const isTarget = t.dataset.tab === tabName
    t.classList.toggle('active', isTarget)
    t.setAttribute('aria-selected', isTarget ? 'true' : 'false')
    t.tabIndex = isTarget ? 0 : -1
  })
  $$('.tab-content').forEach((c) => {
    c.hidden = c.id !== `tab-${tabName}`
    c.classList.toggle('active', c.id === `tab-${tabName}`)
  })
  // Hidden panels report clientWidth 0, so re-measure now that it's visible.
  requestAnimationFrame(updateScrollShadows)
}

function setupMultiSelect() {
  const trigger = $('#model-select-trigger')
  const dropdown = $('#model-select-dropdown')
  const search = $('#model-select-search')

  if (!trigger || !dropdown) return

  trigger.setAttribute('aria-haspopup', 'listbox')
  trigger.setAttribute('aria-expanded', 'false')

  trigger.addEventListener('click', (e) => {
    e.stopPropagation()
    if (!dropdown.hidden) {
      closeDropdown()
    } else {
      if (search) search.value = ''
      filterMultiSelect('')
      dropdown.hidden = false
      trigger.setAttribute('aria-expanded', 'true')
      search?.focus()
    }
  })

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && !dropdown.hidden) {
      closeDropdown()
      trigger.focus()
    }
  })

  document.addEventListener('click', () => closeDropdown())

  dropdown.addEventListener('click', (e) => e.stopPropagation())

  if (search) search.addEventListener('input', () => filterMultiSelect(search.value))

  $('#model-select-all')?.addEventListener('click', selectAllModels)
  $('#model-select-none')?.addEventListener('click', deselectAllModels)
  $('#model-select-top-uptime')?.addEventListener('click', selectTopUptimeModels)

  $('#models-tbody')?.addEventListener('click', (e) => {
    const cell = e.target.closest('.uptime-cell')
    if (cell && cell.dataset.modelId) selectSingleModel(cell.dataset.modelId)
  })

  function closeDropdown() {
    dropdown.hidden = true
    trigger.setAttribute('aria-expanded', 'false')
  }
}

function filterMultiSelect(term) {
  const dropdown = $('#model-select-dropdown')
  if (!dropdown) return
  const needle = term.toLowerCase()
  const options = dropdown.querySelectorAll('.multi-select-option')
  const groups = dropdown.querySelectorAll('.multi-select-group')
  // Toggle `.is-hidden` rather than inline style.display, which made
  // downstream "is this hidden?" checks fragile.
  for (const opt of options) {
    opt.classList.toggle('is-hidden', !opt.textContent?.toLowerCase().includes(needle))
  }
  for (const group of groups) {
    const hidden = group.querySelectorAll('.multi-select-option.is-hidden').length
    const total = group.querySelectorAll('.multi-select-option').length
    const header = group.querySelector('.multi-select-group-header')
    if (header) header.classList.toggle('is-hidden', hidden === total)
  }
}

