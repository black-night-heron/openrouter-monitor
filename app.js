function renderBenchmarks() {
  const tbody = $('#bench-tbody')
  const empty = $('#bench-empty')
  if (!tbody) return
  tbody.innerHTML = ''

  if (!benchmarkRows.length) {
    if (empty) {
      empty.style.display = ''
      empty.textContent = 'No benchmark data yet — scores load on the next refresh.'
    }
    updateScrollShadows()
    return
  }
  if (empty) empty.style.display = 'none'

  const searchTerm = ($('#bench-search').value || '').toLowerCase()
  const freeOnly = $('#bench-free-only')?.checked

  let filtered = [...benchmarkRows]
  if (freeOnly) filtered = filtered.filter((m) => m.isFree)
  if (searchTerm) {
    filtered = filtered.filter(
      (m) => m.name.toLowerCase().includes(searchTerm) || m.id.toLowerCase().includes(searchTerm),
    )
  }

  // Rank is computed over the FULL unfiltered set so `#` stays global.
  const rankByMetric = computeRanking(benchmarkRows, benchSortColumn)

  filtered.sort((a, b) => {
    if (benchSortColumn === 'rank') {
      const ar = rankByMetric.get(a.id) ?? Number.MAX_SAFE_INTEGER
      const br = rankByMetric.get(b.id) ?? Number.MAX_SAFE_INTEGER
      return benchSortDesc ? br - ar : ar - br
    }
    if (benchSortColumn === 'name') {
      return benchSortDesc ? b.name.localeCompare(a.name) : a.name.localeCompare(b.name)
    }
    if (benchSortColumn === 'price') {
      // Sort by combined $/M tokens (prompt+completion); nulls last.
      const cost = (m) => (m.promptPriceUsd != null && m.completionPriceUsd != null)
        ? (m.promptPriceUsd + m.completionPriceUsd) * 1_000_000 : null
      const av = cost(a), bv = cost(b)
      if (av == null && bv == null) return 0
      if (av == null) return 1
      if (bv == null) return -1
      return benchSortDesc ? bv - av : av - bv
    }
    if (benchSortColumn === 'context_length') {
      const av = a.contextLength ?? -1
      const bv = b.contextLength ?? -1
      return benchSortDesc ? bv - av : av - bv
    }
    if (benchSortColumn === 'max_completion_tokens') {
      const av = a.maxCompletionTokens ?? -1
      const bv = b.maxCompletionTokens ?? -1
      return benchSortDesc ? bv - av : av - bv
    }
    const av = metricValue(a, benchSortColumn)
    const bv = metricValue(b, benchSortColumn)
    if (av == null && bv == null) return a.name.localeCompare(b.name)
    if (av == null) return 1
    if (bv == null) return -1
    const cmp = benchSortDesc ? bv - av : av - bv
    return cmp !== 0 ? cmp : a.name.localeCompare(b.name)
  })

  const frag = document.createDocumentFragment()
  for (const m of filtered) {
    const tr = document.createElement('tr')
    const isPinned = radarSelectedIds.has(m.id)
    const isExpanded = expandedBenchIds.has(m.id)
    const hasArena = !!(m.designArena && m.designArena.length)
    if (isPinned) tr.classList.add('bench-row-pinned')
    if (m.isFree) tr.classList.add('bench-row-free')
    if (isExpanded) tr.classList.add('bench-row-expanded')

    const rank = rankByMetric.get(m.id)
    const rankStr = rank != null ? `#${rank}` : '—'
    // Native <button> gives Enter/Space + avoids span double-toggle; rows without
    // arena data keep an invisible placeholder so column width/row height stay identical.
    const chevron = hasArena
      ? `<button type="button" class="bench-chevron${isExpanded ? ' is-expanded' : ''}" aria-expanded="${isExpanded}" aria-label="Toggle Design Arena details for ${escAttr(m.name)}">${isExpanded ? '▾' : '▸'}</button>`
      : '<span class="bench-chevron-slot" aria-hidden="true"></span>'
    const intelStr = scoreCell(m.intelligenceIndex)
    const codingStr = scoreCell(m.codingIndex)
    const agenticStr = scoreCell(m.agenticIndex)
    const arenaStr = renderTopArena(m.designArena)
    const limitsStr = renderLimits(m.contextLength, m.maxCompletionTokens)
    const modsStr = renderModalityBadges(m.inputModalities, m.outputModalities)
    const capsStr = renderCapabilityBadges(m.supportedParameters)
    const priceStr = renderPrice(m)
    const freeBadge = m.isFree ? '<span class="bench-free-badge">FREE</span>' : ''

    tr.dataset.benchId = m.id
    tr.innerHTML = `
      <td class="bench-rank">${chevron}<span class="bench-rank-num">${rankStr}</span></td>
      <td class="bench-name">
        <a href="https://openrouter.ai/models/${escAttr(m.id)}" target="_blank" rel="noopener" class="model-link" title="${escAttr(m.name)}">${esc(m.name)}</a>
        <span class="bench-name-sub"><code title="${escAttr(m.id)}">${esc(m.id)}</code>${freeBadge}</span>
      </td>
      <td class="col-hide-sm num">${intelStr}</td>
      <td class="col-hide-sm num">${codingStr}</td>
      <td class="col-hide-sm num">${agenticStr}</td>
      <td class="col-hide-md">${arenaStr}</td>
      <td class="col-hide-md num" title="Input context limit and maximum output tokens">${limitsStr}</td>
      <td class="col-hide-md">${modsStr}</td>
      <td class="col-hide-md">${capsStr}</td>
      <td class="col-hide-sm num">${priceStr}</td>
    `
    // The chevron and the model link own their own click semantics, so
    // stopPropagation keeps them from also firing the row's radar pin.
    tr.addEventListener('click', (e) => {
      if (e.target.closest('a.model-link')) return
      if (e.target.closest('.bench-chevron')) return
      toggleRadarPin(m.id)
    })
    frag.appendChild(tr)

    if (isExpanded && hasArena) {
      const drawer = document.createElement('tr')
      drawer.classList.add('bench-drawer-row')
      drawer.dataset.benchDrawer = m.id
      // Span the live header count so a column change can't misalign it.
      const span = document.querySelectorAll('#bench-table thead th').length || 1
      drawer.innerHTML = `<td colspan="${span}">${renderBenchDrawer(m)}</td>`
      frag.appendChild(drawer)
    }
  }
  tbody.appendChild(frag)
  updateScrollShadows()
}

/** Map each model id → its 1-based rank by the active sort metric. */
function computeRanking(rows, metric) {
  const ranked = [...rows].sort((a, b) => {
    const av = metricValue(a, metric)
    const bv = metricValue(b, metric)
    if (av == null && bv == null) return a.name.localeCompare(b.name)
    if (av == null) return 1
    if (bv == null) return -1
    const cmp = bv - av
    return cmp !== 0 ? cmp : a.name.localeCompare(b.name)
  })
  const map = new Map()
  for (let i = 0; i < ranked.length; i++) map.set(ranked[i].id, i + 1)
  return map
}

function metricValue(m, key) {
  if (key === 'intelligence_index') return m.intelligenceIndex
  if (key === 'coding_index') return m.codingIndex
  if (key === 'agentic_index') return m.agenticIndex
  return null
}

/** A score cell with a heatmap-style color band proportional to value (0-100). */
function scoreCell(v, title) {
  if (v == null) return '<span class="text-muted">—</span>'
  const color = scoreColor(v)
  const pct = Math.max(0, Math.min(100, v))
  return `<span class="score-pill" style="--score-color:${color};--score-pct:${pct}%" title="${escAttr(title || `${v.toFixed(1)} / 100`)}">${v.toFixed(1)}</span>`
}

function scoreColor(v) {
  // 0-100 scale; tiered color so the leaderboard reads at a glance.
  if (v >= 70) return 'var(--green)'
  if (v >= 55) return 'var(--lime)'
  if (v >= 40) return 'var(--amber)'
  if (v >= 25) return 'var(--orange)'
  return 'var(--red)'
}

