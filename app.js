/** Toggle a row's Design Arena drawer. Re-renders, then restores focus to the
 *  new chevron — the re-render destroyed the one the keyboard user activated. */
function toggleBenchDrawer(id) {
  if (expandedBenchIds.has(id)) expandedBenchIds.delete(id)
  else expandedBenchIds.add(id)
  renderBenchmarks()
  const chev = document.querySelector(`tr[data-bench-id="${cssEsc(id)}"] .bench-chevron`)
  if (chev instanceof HTMLElement) chev.focus()
}

function groupArenaEntries(designArena) {
  const byArena = new Map()
  for (const e of designArena) {
    if (!byArena.has(e.arena)) byArena.set(e.arena, [])
    byArena.get(e.arena).push(e)
  }
  const groups = []
  for (const [arena, entries] of byArena) {
    entries.sort((a, b) => b.elo - a.elo || a.rank - b.rank)
    groups.push({ arena, entries })
  }
  groups.sort((a, b) => b.entries[0].elo - a.entries[0].elo)
  return groups
}

function arenaEloColor(elo) {
  if (elo >= 1400) return 'var(--green)'
  if (elo >= 1300) return 'var(--lime)'
  if (elo >= 1200) return 'var(--amber)'
  if (elo >= 1100) return 'var(--orange)'
  return 'var(--red)'
}

/** Bar width % on the fixed ARENA_ELO_MIN..MAX scale, clamped to [2, 100]. */
function arenaEloWidth(elo) {
  const pct = ((elo - ARENA_ELO_MIN) / (ARENA_ELO_MAX - ARENA_ELO_MIN)) * 100
  return Math.max(2, Math.min(100, pct))
}

function renderBenchDrawer(m) {
  const entries = m.designArena || []
  const groups = groupArenaEntries(entries)
  const total = entries.length

  const groupHtml = groups.map((g) => {
    const bars = g.entries.map((e) => {
      // design_arena comes from JSON.parse with no validation; a missing
      // win_rate would throw and blank the whole leaderboard.
      const elo = typeof e.elo === 'number' ? e.elo : null
      const winRate = typeof e.win_rate === 'number' ? e.win_rate : null
      const rank = typeof e.rank === 'number' ? e.rank : null
      const color = elo != null ? arenaEloColor(elo) : 'var(--text-muted)'
      const width = elo != null ? arenaEloWidth(elo) : 0
      const isTop = e === g.entries[0]
      const eloStr = elo != null ? String(elo) : '—'
      const winStr = winRate != null ? `${Math.round(winRate)}%` : '—'
      const rankStr = rank != null ? `#${rank}` : '—'
      return `
        <li class="arena-bar-row${isTop ? ' arena-bar-top' : ''}">
          <span class="arena-bar-cat" title="${escAttr(arenaLabel(g.arena))} / ${escAttr(arenaLabel(e.category))}">${esc(arenaLabel(e.category))}</span>
          <span class="arena-bar-track">
            <span class="arena-bar-fill" style="width:${width}%;background:${color}"></span>
          </span>
          <span class="arena-bar-elo" style="color:${color}">${eloStr}</span>
          <span class="arena-bar-meta">${winStr} · ${rankStr}</span>
        </li>`
    }).join('')
    return `
      <div class="arena-group">
        <div class="arena-group-header">
        <span class="arena-group-label">${esc(arenaLabel(g.arena))}</span>
          <span class="arena-group-count">${g.entries.length} categor${g.entries.length === 1 ? 'y' : 'ies'}</span>
        </div>
        <ul class="arena-bars">${bars}</ul>
      </div>`
  }).join('')

  return `
    <div class="bench-drawer">
      <div class="bench-drawer-header">
        <span class="bench-drawer-title">${esc(m.name)} — Design Arena</span>
        <span class="bench-drawer-sub">${total} categor${total === 1 ? 'y' : 'ies'} across ${groups.length} arena${groups.length === 1 ? '' : 's'} · Bars scaled Elo ${ARENA_ELO_MIN}–${ARENA_ELO_MAX}</span>
      </div>
      <div class="bench-drawer-groups">${groupHtml}</div>
    </div>`
}

/** Stacked "Limits" cell: context length over max output — a 1M-context model
 *  with a 128K output cap is not the same as one that can emit 1M. */
function renderLimits(contextLength, maxCompletionTokens) {
  const ctx = formatContext(contextLength)
  const out = formatContext(maxCompletionTokens)
  if (ctx === '—' && out === '—') return '<span class="text-muted">—</span>'
  return `<span class="cell-stack limits-cell"><strong>${ctx}</strong><span class="cell-sub">${out === '—' ? 'out —' : 'out ' + out}</span></span>`
}

function renderModalityBadges(inputMods, outputMods) {
  const IN = { text: 'T', image: 'I', audio: 'A', file: 'F', video: 'V' }
  const OUT = { text: 'T', image: 'I', audio: 'A', file: 'F', video: 'V' }
  const chip = (mo, dir, map) => {
    const label = map[mo] ?? mo.charAt(0).toUpperCase()
    return `<span class="mod-chip mod-chip-${dir}" title="${dir === 'in' ? 'Input' : 'Output'}: ${capitalize(escAttr(mo))}">${label}</span>`
  }
  const inChips = (inputMods || []).slice(0, 5).map((mo) => chip(mo, 'in', IN))
  const outChips = (outputMods || []).slice(0, 5).map((mo) => chip(mo, 'out', OUT))
  if (!inChips.length && !outChips.length) return '<span class="text-muted">—</span>'
  return `${inChips.join('')}<span class="mod-arrow" aria-hidden="true">→</span>${outChips.join('')}`
}

/** Capability chips from `supported_parameters`, capped at 4 — a model
 *  typically supports ~11, and an uncapped row is noise. */
const CAPABILITY_CHIPS = [
  { key: 'tools', label: 'Tool', title: 'Accepts tool / function calls' },
  { key: 'structured_outputs', label: 'JSON', title: 'Returns structured JSON output' },
  { key: 'reasoning', label: 'Reason', title: 'Supports a reasoning / thinking mode' },
  { key: 'response_format', label: 'Fmt', title: 'Accepts a response_format parameter' },
  { key: 'verbosity', label: 'Verb', title: 'Accepts a verbosity parameter' },
  { key: 'web_search', label: 'Web', title: 'Supports the web_search tool' },
]
const CAPABILITY_CHIP_LIMIT = 4

function renderCapabilityBadges(params) {
  if (!params || !params.length) return '<span class="text-muted">—</span>'
  const set = new Set(params)
  const matched = CAPABILITY_CHIPS.filter((c) => set.has(c.key))
  if (!matched.length) {
    // Fall back to a count so the column is never mysteriously blank.
    return `<span class="cap-chip cap-chip-more" title="${params.length} supported parameters">+${params.length}</span>`
  }
  const shown = matched.slice(0, CAPABILITY_CHIP_LIMIT)
  const chips = shown.map((c) => `<span class="cap-chip" title="${c.title}">${c.label}</span>`)
  const hidden = params.length - shown.length
  if (hidden > 0) {
    chips.push(
      `<span class="cap-chip cap-chip-more" title="${hidden} more supported parameters">+${hidden}</span>`,
    )
  }
  return chips.join('')
}

function renderPrice(m) {
  const p = m.promptPriceUsd
  const c = m.completionPriceUsd
  if (p == null && c == null) return '<span class="text-muted">—</span>'
  if (p === 0 && c === 0) return '<span class="bench-free-price">FREE</span>'
  // Display $/M tokens (prompt+completion) for readability.
  const perM = ((p ?? 0) + (c ?? 0)) * 1_000_000
  if (perM === 0) return '<span class="bench-free-price">FREE</span>'
  return `<span class="bench-price">$${perM < 1 ? perM.toFixed(2) : perM.toFixed(0)}/M</span>`
}

function toggleRadarPin(id) {
  if (radarSelectedIds.has(id)) {
    radarSelectedIds.delete(id)
  } else {
    if (radarSelectedIds.size >= RADAR_MAX_SELECTION) {
      // Drop the oldest pin (Set preserves insertion order) to make room.
      const first = radarSelectedIds.values().next().value
      if (first) radarSelectedIds.delete(first)
    }
    radarSelectedIds.add(id)
  }
  syncBenchRowPinState()
  renderRadarChart()
}

function syncBenchRowPinState() {
  const countEl = $('#compare-selected-count')
  if (countEl) {
    countEl.textContent = `${radarSelectedIds.size} / ${RADAR_MAX_SELECTION}`
    countEl.classList.toggle('is-active', radarSelectedIds.size > 0)
  }
  document.querySelectorAll('#bench-tbody tr').forEach((tr) => {
    const id = tr.dataset.benchId
    tr.classList.toggle('bench-row-pinned', id != null && radarSelectedIds.has(id))
  })
}

function renderRadarChart() {
  const empty = $('#radar-empty')
  const card = $('.compare-radar-card')

  if (radarSelectedIds.size === 0) {
    destroyChartOn($('#radar-chart'))
    radarChart = null
    // Collapse the canvas out of layout so the card shrinks to the
    // empty-state height.
    card?.classList.add('is-empty')
    if (empty) {
      empty.style.display = ''
      empty.innerHTML = '<span class="empty-title">Nothing pinned yet</span>Click any row in the leaderboard to overlay it here. Up to 5 models at a time.'
    }
    syncBenchRowPinState()
    return
  }

  card?.classList.remove('is-empty')
  if (empty) empty.style.display = 'none'

  // Resolve pins by id so a refresh reordering the leaderboard is safe.
  const byId = new Map(benchmarkRows.map((m) => [m.id, m]))
  const pinned = [...radarSelectedIds].map((id) => byId.get(id)).filter(Boolean)

  const CHART_COLORS = getChartColors()
  const t = chartTheme()

  const datasets = pinned.map((m, i) => {
    const color = CHART_COLORS[i % CHART_COLORS.length]
    return {
      label: m.name,
      // A missing benchmark index plots as 0 to keep the polygon closed;
      // the tooltip shows the true '—'.
      data: RADAR_AXES.map((axis) => {
        const v = metricValue(m, axis)
        return v != null ? v : 0
      }),
      borderColor: color,
      backgroundColor: hexToRgba(color, 0.12),
      pointBackgroundColor: color,
      pointBorderColor: color,
      pointRadius: 3,
      pointHoverRadius: 5,
      borderWidth: 2,
    }
  })

  const ctx = $('#radar-chart').getContext('2d')
  const options = {
    responsive: true,
    maintainAspectRatio: false,
    animation: false,
    plugins: {
      legend: {
        display: true,
        position: 'bottom',
        align: 'start',
        labels: {
          color: t.tick,
          padding: 10,
          font: { size: 11, family: 'Inter, -apple-system, sans-serif' },
          boxWidth: 11,
          boxHeight: 11,
          useBorderRadius: true,
          borderRadius: 3,
        },
      },
      tooltip: {
        backgroundColor: t.tooltipBg,
        titleColor: t.label,
        bodyColor: t.tick,
        borderColor: t.tooltipBorder,
        borderWidth: 1,
        cornerRadius: 8,
        padding: 10,
        bodyFont: { family: 'Inter, -apple-system, sans-serif', size: 12 },
        callbacks: {
          label: (ctx) => {
            const axis = RADAR_AXES[ctx.dataIndex]
            const m = pinned[ctx.datasetIndex]
            const v = m ? metricValue(m, axis) : null
            return `${ctx.dataset.label}: ${v != null ? v.toFixed(1) : '—'}`
          },
        },
      },
    },
    scales: {
      r: {
        min: 0,
        max: 100,
        beginAtZero: true,
        ticks: {
          color: t.tick,
          backdropColor: 'transparent',
          stepSize: 20,
          font: { size: 9 },
        },
        grid: { color: t.isDark ? 'rgba(255,255,255,0.08)' : 'rgba(0,0,0,0.06)' },
        angleLines: { color: t.isDark ? 'rgba(255,255,255,0.08)' : 'rgba(0,0,0,0.06)' },
        pointLabels: {
          color: t.label,
          font: { size: 12, weight: 600, family: 'Inter, -apple-system, sans-serif' },
        },
      },
    },
  }

  destroyChartOn(ctx.canvas)
  radarChart = new Chart(ctx, {
    type: 'radar',
    data: { labels: RADAR_LABELS, datasets },
    options,
  })
  syncBenchRowPinState()
}

// ── Helpers ─────────────────────────────────────────────────────────────────
/** Escape for use inside a CSS attribute selector; ids are bare slugs that
 *  can contain `/` and `.`, and a `"` would break out of the value. */
function cssEsc(str) {
  return String(str).replace(/(["\\])/g, '\\$1')
}

function esc(str) {
  if (!str) return ''
  const div = document.createElement('div')
  div.textContent = str
  return div.innerHTML
}

function capitalize(s) {
  if (!s) return ''
  return String(s).charAt(0).toUpperCase() + String(s).slice(1)
}

/** Best label for an owner slug: the vendor's own `provider_name` casing, but only
 *  when the provider's slug prefix matches the owner (else `dots-studio` mislabels as "AtlasCloud"). */
let ownerLabelCache = { rows: null, map: new Map() }

function ownerLabelMap() {
  if (ownerLabelCache.rows === allModels) return ownerLabelCache.map
  const map = new Map()
  for (const m of allModels) {
    if (!m.owner || map.has(m.owner)) continue
    for (const p of m.providers) {
      const prefix = normSlug(String(p.slug || '').split('/')[0])
      if (prefix && prefix === normSlug(m.owner)) {
        map.set(m.owner, p.name)
        break
      }
    }
  }
  ownerLabelCache = { rows: allModels, map }
  return map
}

function ownerLabel(owner) {
  if (!owner) return ''
  const firstParty = ownerLabelMap().get(owner)
  return firstParty || titleCaseSlug(owner)
}

function titleCaseSlug(slug) {
  return String(slug)
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => capitalize(part))
    .join(' ')
}

function normSlug(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '')
}

function escAttr(str) {
  if (!str) return ''
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

function hexToRgba(hex, alpha) {
  let clean = hex.replace('#', '')
  if (clean.length === 8) clean = clean.substring(0, 6)
  if (clean.length === 3) {
    const r = parseInt(clean[0] + clean[0], 16)
    const g = parseInt(clean[1] + clean[1], 16)
    const b = parseInt(clean[2] + clean[2], 16)
    return `rgba(${r},${g},${b},${alpha})`
  }
  const r = parseInt(clean.substring(0, 2), 16)
  const g = parseInt(clean.substring(2, 4), 16)
  const b = parseInt(clean.substring(4, 6), 16)
  return `rgba(${r},${g},${b},${alpha})`
}
