function setupTabs() {
  const tabs = $$('.tab')

  function activate(name) {
    switchTab(name)
    if (name === 'trends') loadModelUptimeChart()
    if (name === 'compare') {
      // Lazy-load benchmarks the first time the Compare tab is opened;
      // later refresh ticks call refreshBenchmarks() to stay in sync.
      if (!benchHasLoaded) {
        benchHasLoaded = true
        refreshBenchmarks()
      } else {
        renderBenchmarks()
        renderRadarChart()
      }
    }
  }

  tabs.forEach((tab, i) => {
    tab.addEventListener('click', () => activate(tab.dataset.tab))

    // Roving-tabindex arrow navigation, per the WAI-ARIA tabs pattern.
    tab.addEventListener('keydown', (e) => {
      const delta = e.key === 'ArrowRight' ? 1 : e.key === 'ArrowLeft' ? -1 : 0
      if (!delta) return
      e.preventDefault()
      const next = tabs[(i + delta + tabs.length) % tabs.length]
      activate(next.dataset.tab)
      next.focus()
    })
  })
}

