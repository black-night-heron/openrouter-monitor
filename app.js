/** Label for an arena/category slug; unmapped slugs degrade to title case so a
 *  new upstream category reads cleanly instead of leaking raw casing. */
function arenaLabel(slug) {
  if (!slug) return ''
  const known = ARENA_LABELS[slug]
  if (known) return known
  return String(slug)
    .replace(/\(([^)]*)\)/g, ' ($1) ')
    .split(/[^a-z0-9]+/i)
    .filter(Boolean)
    .map(capitalize)
    .join(' ')
}

/** Highest-Elo Design Arena category as a compact chip. */
function renderTopArena(designArena) {
  if (!designArena || !designArena.length) return '<span class="text-muted">—</span>'
  // Highest Elo wins; tiebreak by lowest rank (rank 1 = best in category).
  let best = designArena[0]
  for (const e of designArena) {
    if (e.elo > best.elo || (e.elo === best.elo && e.rank < best.rank)) best = e
  }
  const full = arenaLabel(best.category)
  // Chip width is bounded by the cell; the full name lives in the tooltip.
  const label = full.length > ARENA_CHIP_LABEL_MAX ? full.slice(0, ARENA_CHIP_LABEL_MAX - 1) + '…' : full
  return `<span class="arena-chip" title="${escAttr(arenaLabel(best.arena))} / ${escAttr(full)} · Elo ${String(best.elo)} · Rank #${String(best.rank)} · Win Rate ${String(best.win_rate)}%">${esc(label)} <strong>${String(best.elo)}</strong></span>`
}

